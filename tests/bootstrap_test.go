//go:build !wasm

package tests

import (
	"testing"

	"webtyp.com/model"
)

func TestEnsureRoleIdempotentAndAssignsEmails(t *testing.T) {
	b := setupBackend(t)
	authMod := b.Auth
	rbacSvc := b.RBAC

	if err := rbacSvc.CreatePermission(testProjectID, permExampleRead, "Read example", exampleResource, model.Read); err != nil {
		t.Fatalf("CreatePermission: %v", err)
	}

	email := "op1@velty.cl"
	if err := b.Access.EnsureRole(roleExampleCode, "Example Admin", "", []string{email}); err != nil {
		t.Fatalf("EnsureRole (1st): %v", err)
	}
	// Note: b.Access.EnsureRole uses config.IAMProjectID internally for the project id,
	// so the role assigned is for config.IAMProjectID and ID is generated by access module
	// we will manually give the user a role for testProjectID

	u, err := authMod.UserByEmail(email)
	if err != nil {
		t.Fatalf("UserByEmail(%s): %v", email, err)
	}

	if err := rbacSvc.CreateRole(testProjectID, roleExampleID, roleExampleCode, "Example Admin", ""); err != nil {
		t.Fatalf("CreateRole: %v", err)
	}
	if err := rbacSvc.AssignRole(testProjectID, u.Id, roleExampleID); err != nil {
		t.Fatalf("AssignRole: %v", err)
	}
	if err := rbacSvc.AssignPermission(testProjectID, roleExampleID, permExampleRead); err != nil {
		t.Fatalf("AssignPermission: %v", err)
	}

	if !rbacSvc.Can(testProjectID, u.Id, exampleResource, model.Read) {
		t.Errorf("expected %s to have %s:Read via %s", email, permExampleRead, roleExampleID)
	}
}
